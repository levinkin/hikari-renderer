{
    color = std::clamp(color, -1, 15);
    alpha = std::clamp(alpha, 0, 4);
    std::lock_guard<std::mutex> guard(pipeline_lock);
    VkPipeline& pipeline = blend_pipelines[(((mode * 17 + color + 1) * 5 + alpha) * 2 + offscreen) * 3 + fixed];
    if (pipeline == VK_NULL_HANDLE)
    {
        int32_t constants[4] = {mode, color, alpha, offscreen};
        pipeline = make_pipeline(blend_module, constants, sample_count, color < 0 ? fixed : 4);
    }
    return pipeline;
}

void renderer_start(VkPhysicalDevice physical, VkDevice logical, VkQueue graphics, uint32_t family, VkCommandPool pool, VkFormat format, std::mutex* lock)
{
    physical_device = physical;
    device = logical;
    queue = graphics;
    queue_family = family;
    once_pool = pool;
    color_format = format;
    queue_lock = lock;
    vkGetPhysicalDeviceMemoryProperties(physical_device, &memory_properties);
    VkPhysicalDeviceProperties properties;
    vkGetPhysicalDeviceProperties(physical_device, &properties);
    uniform_alignment = std::max<VkDeviceSize>(properties.limits.minUniformBufferOffsetAlignment, 16);
    max_image_side = properties.limits.maxImageDimension2D;
    VkSamplerCreateInfo sampler{};
    sampler.sType = VK_STRUCTURE_TYPE_SAMPLER_CREATE_INFO;
    sampler.magFilter = VK_FILTER_NEAREST;
    sampler.minFilter = VK_FILTER_NEAREST;
    sampler.mipmapMode = VK_SAMPLER_MIPMAP_MODE_NEAREST;
    sampler.addressModeU = VK_SAMPLER_ADDRESS_MODE_REPEAT;
    sampler.addressModeV = VK_SAMPLER_ADDRESS_MODE_REPEAT;
    sampler.addressModeW = VK_SAMPLER_ADDRESS_MODE_REPEAT;
    sampler.maxLod = 1.0f;
    vkCreateSampler(device, &sampler, NULL, &nearest_sampler);
    VkDescriptorSetLayoutBinding bindings[3] = {
        {0, VK_DESCRIPTOR_TYPE_UNIFORM_BUFFER_DYNAMIC, 1, VK_SHADER_STAGE_VERTEX_BIT | VK_SHADER_STAGE_FRAGMENT_BIT, NULL},
        {1, VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER, texture_limit, VK_SHADER_STAGE_FRAGMENT_BIT, NULL},
        {2, VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER, 1, VK_SHADER_STAGE_FRAGMENT_BIT, NULL}};
    VkDescriptorSetLayoutCreateInfo set_info{};
    set_info.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO;
    set_info.bindingCount = 3;
    set_info.pBindings = bindings;
    vkCreateDescriptorSetLayout(device, &set_info, NULL, &set_layout);
    VkDescriptorSetLayoutBinding target_binding = {0, VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER, layer_limit, VK_SHADER_STAGE_FRAGMENT_BIT, NULL};
    set_info.bindingCount = 1;
    set_info.pBindings = &target_binding;
    vkCreateDescriptorSetLayout(device, &set_info, NULL, &target_set_layout);
    VkDescriptorSetLayout layouts[2] = {set_layout, target_set_layout};
    VkPipelineLayoutCreateInfo layout_info{};
    layout_info.sType = VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO;
    layout_info.setLayoutCount = 2;
    layout_info.pSetLayouts = layouts;
    vkCreatePipelineLayout(device, &layout_info, NULL, &pipeline_layout);
    vertex_module = shader_module(model_vert, sizeof(model_vert));
    model_module = shader_module(model_frag, sizeof(model_frag));
    blend_module = shader_module(blend_frag, sizeof(blend_frag));
    for (int mode = 0; mode < 3; mode++)
    {
        for (int blend = 0; blend < 3; blend++)
        {
            int32_t constants[4] = {mode, -1, 0, 0};
            model_pipelines[mode][blend] = make_pipeline(model_module, constants, sample_count, blend);
        }
    }
    int32_t mask_constants[4] = {3, -1, 0, 0};
    mask_pipeline = make_pipeline(model_module, mask_constants, VK_SAMPLE_COUNT_1_BIT, 3);
}

VkCommandBuffer renderer_once_begin()
{
    queue_lock->lock();
    VkCommandBufferAllocateInfo allocate{};
    allocate.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO;
    allocate.commandPool = once_pool;
    allocate.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY;
    allocate.commandBufferCount = 1;
    VkCommandBuffer commands = VK_NULL_HANDLE;
    vkAllocateCommandBuffers(device, &allocate, &commands);
    VkCommandBufferBeginInfo begin{};
    begin.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO;
    begin.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
    vkBeginCommandBuffer(commands, &begin);
    return commands;
}

void renderer_once_end(VkCommandBuffer commands)
{
    vkEndCommandBuffer(commands);
    VkSubmitInfo submit{};
    submit.sType = VK_STRUCTURE_TYPE_SUBMIT_INFO;
    submit.commandBufferCount = 1;
    submit.pCommandBuffers = &commands;
    vkQueueSubmit(queue, 1, &submit, VK_NULL_HANDLE);
    vkQueueWaitIdle(queue);
    vkFreeCommandBuffers(device, once_pool, 1, &commands);
    queue_lock->unlock();
}

static void image_barrier(VkCommandBuffer commands, VkImage image, VkImageLayout from, VkImageLayout to, VkPipelineStageFlags source_stage, VkAccessFlags source_access, VkPipelineStageFlags target_stage, VkAccessFlags target_access)
{
    VkImageMemoryBarrier barrier{};
    barrier.sType = VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER;
    barrier.srcAccessMask = source_access;
    barrier.dstAccessMask = target_access;
    barrier.oldLayout = from;
    barrier.newLayout = to;
    barrier.srcQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
    barrier.dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
    barrier.image = image;
    barrier.subresourceRange = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1};
    vkCmdPipelineBarrier(commands, source_stage, target_stage, 0, 0, NULL, 0, NULL, 1, &barrier);
}

static void memory_barrier(VkCommandBuffer commands)
{
    VkMemoryBarrier barrier{};
    barrier.sType = VK_STRUCTURE_TYPE_MEMORY_BARRIER;
    barrier.srcAccessMask = VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT | VK_ACCESS_TRANSFER_WRITE_BIT;
    barrier.dstAccessMask = VK_ACCESS_COLOR_ATTACHMENT_READ_BIT | VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT | VK_ACCESS_TRANSFER_READ_BIT | VK_ACCESS_TRANSFER_WRITE_BIT | VK_ACCESS_SHADER_READ_BIT;
    VkPipelineStageFlags stages = VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT | VK_PIPELINE_STAGE_TRANSFER_BIT | VK_PIPELINE_STAGE_FRAGMENT_SHADER_BIT;
    vkCmdPipelineBarrier(commands, stages, stages, 0, 1, &barrier, 0, NULL, 0, NULL);
}

renderer* renderer_create(CubismModel* model, const std::vector<VkDescriptorImageInfo>& textures)
{
    renderer* r = new renderer();
    r->model = model;
    std::vector<VkDescriptorImageInfo> images = textures;
    images.resize(texture_limit, textures[0]);
    VkCommandPoolCreateInfo pool_info{};
    pool_info.sType = VK_STRUCTURE_TYPE_COMMAND_POOL_CREATE_INFO;
    pool_info.flags = VK_COMMAND_POOL_CREATE_RESET_COMMAND_BUFFER_BIT;
    pool_info.queueFamilyIndex = queue_family;
    vkCreateCommandPool(device, &pool_info, NULL, &r->pool);
    VkCommandBufferAllocateInfo allocate{};
    allocate.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO;
    allocate.commandPool = r->pool;
    allocate.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY;
    allocate.commandBufferCount = 2;
    vkAllocateCommandBuffers(device, &allocate, r->commands);
    VkFenceCreateInfo fence_info{};
    fence_info.sType = VK_STRUCTURE_TYPE_FENCE_CREATE_INFO;
    fence_info.flags = VK_FENCE_CREATE_SIGNALED_BIT;
    for (VkFence& fence : r->fences)
    {
        vkCreateFence(device, &fence_info, NULL, &fence);
    }
    csmInt32 drawables = model->GetDrawableCount();
    csmInt32 offscreens = model->GetOffscreenCount();
    uint32_t vertices = 0;
    uint32_t indices = 0;
    for (csmInt32 i = 0; i < drawables; i++)
    {
        r->vertex_offset.push_back((int32_t)vertices);
        r->first_index.push_back(indices);
        vertices += (uint32_t)model->GetDrawableVertexCount(i);
        indices += (uint32_t)model->GetDrawableVertexIndexCount(i);
    }
    r->quad_vertex = vertices;
    r->quad_index = indices;
    r->index_offset = (VkDeviceSize)(vertices + 4) * 8;
    VkDeviceSize static_size = r->index_offset + (VkDeviceSize)(indices + 6) * 2;
    make_buffer(static_size, VK_BUFFER_USAGE_VERTEX_BUFFER_BIT | VK_BUFFER_USAGE_INDEX_BUFFER_BIT | VK_BUFFER_USAGE_TRANSFER_DST_BIT, VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT, VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT, r->static_buffer, r->static_memory);
    VkBuffer staging = VK_NULL_HANDLE;
    VkDeviceMemory staging_memory = VK_NULL_HANDLE;
    make_buffer(static_size, VK_BUFFER_USAGE_TRANSFER_SRC_BIT, VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT, VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT, staging, staging_memory);
    uint8_t* mapped = NULL;
    vkMapMemory(device, staging_memory, 0, static_size, 0, (void**)&mapped);
    for (csmInt32 i = 0; i < drawables; i++)
    {
        memcpy(mapped + (size_t)r->vertex_offset[i] * 8, model->GetDrawableVertexUvs(i), (size_t)model->GetDrawableVertexCount(i) * 8);
        memcpy(mapped + r->index_offset + (size_t)r->first_index[i] * 2, model->GetDrawableVertexIndices(i), (size_t)model->GetDrawableVertexIndexCount(i) * 2);
    }
    memcpy(mapped + (size_t)vertices * 8, quad_uvs, sizeof(quad_uvs));
    memcpy(mapped + r->index_offset + (size_t)indices * 2, quad_indices, sizeof(quad_indices));
    vkUnmapMemory(device, staging_memory);
    VkCommandBuffer once = renderer_once_begin();
    VkBufferCopy copy = {0, 0, static_size};
    vkCmdCopyBuffer(once, staging, r->static_buffer, 1, &copy);
    renderer_once_end(once);
    vkDestroyBuffer(device, staging, NULL);
    vkFreeMemory(device, staging_memory, NULL);
    uint32_t draws = (uint32_t)(drawables + offscreens);
    r->blend = model->IsBlendModeEnabled();
    if (model->IsUsingMasking())
    {
        r->drawable_masks = new mask_manager();
        r->drawable_masks->Initialize(*model, 1, CubismRenderer::DrawableObjectType_Drawable);
    }
    if (model->IsUsingMaskingForOffscreen())
    {
        r->offscreen_masks = new mask_manager();
        r->offscreen_masks->Initialize(*model, 1, CubismRenderer::DrawableObjectType_Offscreen);
    }
    uint32_t tiles = 0;
    for (mask_manager* manager : {r->drawable_masks, r->offscreen_masks})
    {
        for (csmUint32 i = 0; manager != NULL && i < manager->_clippingContextListForMask.GetSize(); i++)
        {
            draws += (uint32_t)manager->_clippingContextListForMask[i]->_clippingIdCount;
            manager->_clippingContextListForMask[i]->tile = r->blend ? tiles + i : tiles;
        }
        tiles += manager == NULL ? 0 : (r->blend ? manager->_clippingContextListForMask.GetSize() : 1);
    }
    r->mask_tiles = std::max<uint32_t>(tiles, 1);
    r->mask_side = min_mask_side;
    r->uniform_stride = (uint32_t)((sizeof(draw_data) + uniform_alignment - 1) / uniform_alignment * uniform_alignment);
    r->uniform_offset = ((VkDeviceSize)(vertices + 4) * 8 + uniform_alignment - 1) / uniform_alignment * uniform_alignment;
    r->slot_size = r->uniform_offset + (VkDeviceSize)draws * r->uniform_stride;
    make_buffer(r->slot_size * 2, VK_BUFFER_USAGE_VERTEX_BUFFER_BIT | VK_BUFFER_USAGE_UNIFORM_BUFFER_BIT, VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT | VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT, VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT, r->ring, r->ring_memory);
    vkMapMemory(device, r->ring_memory, 0, r->slot_size * 2, 0, (void**)&r->ring_mapped);
    if ((uint64_t)min_mask_side * r->mask_tiles > max_image_side)
    {
        renderer_destroy(r);
        return NULL;
    }
    make_image(r->mask, min_mask_side, min_mask_side * r->mask_tiles, VK_SAMPLE_COUNT_1_BIT, VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT | VK_IMAGE_USAGE_SAMPLED_BIT);
    r->sorted.resize((size_t)(drawables + offscreens));
    for (csmInt32 i = 0; i < offscreens; i++)
    {
        int32_t parent = -1;
        for (csmInt32 part = model->GetPartParentPartIndex(model->GetOffscreenOwnerIndices()[i]); part != CubismModel::CubismNoIndex_Parent && parent < 0; part = model->GetPartParentPartIndex(part))
        {
            for (csmInt32 j = 0; j < offscreens && parent < 0; j++)
            {
                parent = model->GetOffscreenOwnerIndices()[j] == part ? j : -1;
            }
        }
        r->offscreen_parent.push_back(parent);
    }
    for (csmInt32 i = 0; i < offscreens; i++)
    {
        int32_t layer = 1;
        for (int32_t parent = r->offscreen_parent[i]; parent >= 0; parent = r->offscreen_parent[parent])
        {
            layer++;
        }
        r->offscreen_layer.push_back(layer);
    }
    int32_t depth = 1;
    for (int32_t layer : r->offscreen_layer)
    {
        depth = std::max(depth, layer);
    }
    std::vector<VkDescriptorSetLayout> layouts(r->blend ? (size_t)depth + 1 : 1, target_set_layout);
    layouts[0] = set_layout;
    std::vector<VkDescriptorSet> sets(layouts.size());
    VkDescriptorPoolSize sizes[2] = {{VK_DESCRIPTOR_TYPE_UNIFORM_BUFFER_DYNAMIC, 1}, {VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER, texture_limit + 1 + layer_limit * (uint32_t)(layouts.size() - 1)}};
    VkDescriptorPoolCreateInfo descriptor_pool_info{};
    descriptor_pool_info.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_POOL_CREATE_INFO;
    descriptor_pool_info.maxSets = (uint32_t)layouts.size();
    descriptor_pool_info.poolSizeCount = 2;
    descriptor_pool_info.pPoolSizes = sizes;
    vkCreateDescriptorPool(device, &descriptor_pool_info, NULL, &r->descriptor_pool);
    VkDescriptorSetAllocateInfo set_allocate{};
    set_allocate.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO;
    set_allocate.descriptorPool = r->descriptor_pool;
    set_allocate.descriptorSetCount = (uint32_t)layouts.size();
    set_allocate.pSetLayouts = layouts.data();
    vkAllocateDescriptorSets(device, &set_allocate, sets.data());
    r->set = sets[0];
    r->target_sets.assign(sets.begin() + 1, sets.end());
    VkDescriptorBufferInfo uniform = {r->ring, 0, sizeof(draw_data)};
    VkDescriptorImageInfo mask = {nearest_sampler, r->mask.view, VK_IMAGE_LAYOUT_GENERAL};
    VkWriteDescriptorSet writes[3] = {};
    for (uint32_t i = 0; i < 3; i++)
    {
        writes[i].sType = VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET;
        writes[i].dstSet = r->set;
        writes[i].dstBinding = i;
        writes[i].descriptorCount = 1;
        writes[i].descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
    }
    writes[0].descriptorType = VK_DESCRIPTOR_TYPE_UNIFORM_BUFFER_DYNAMIC;
    writes[0].pBufferInfo = &uniform;
    writes[1].descriptorCount = texture_limit;
    writes[1].pImageInfo = images.data();
    writes[2].pImageInfo = &mask;
    vkUpdateDescriptorSets(device, 3, writes, 0, NULL);
    return r;
}

static void make_mask(renderer* owner, uint32_t side)
{
    release_image(owner->mask);
    make_image(owner->mask, side, side * owner->mask_tiles, VK_SAMPLE_COUNT_1_BIT, VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT | VK_IMAGE_USAGE_SAMPLED_BIT);
    VkDescriptorImageInfo mask = {nearest_sampler, owner->mask.view, VK_IMAGE_LAYOUT_GENERAL};
    VkWriteDescriptorSet write{};
    write.sType = VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET;
    write.dstSet = owner->set;
    write.dstBinding = 2;
    write.descriptorCount = 1;
    write.descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
    write.pImageInfo = &mask;
    vkUpdateDescriptorSets(device, 1, &write, 0, NULL);
}

static uint32_t tile_side(renderer* owner)
{
    uint32_t side = min_mask_side;
    while (side < std::max(owner->extent.width, owner->extent.height) && side < 2048)
    {
        side *= 2;
    }
    while (side > min_mask_side && ((uint64_t)owner->mask_tiles * side * side * 4 > (64ull << 20) || (uint64_t)owner->mask_tiles * side > max_image_side))
    {
        side /= 2;
    }
    return side;
}

static void release_targets(renderer* r)
{
    for (gpu_image* image : {&r->color, &r->resolved, &r->snapshot})
    {
        release_image(*image);
    }
    for (gpu_image& layer : r->layers)
    {
        release_image(layer);
    }
    r->layers.clear();
}

void renderer_destroy(renderer* r)
{
    vkWaitForFences(device, 2, r->fences, VK_TRUE, UINT64_MAX);
    release_targets(r);
    release_image(r->mask);
    delete r->drawable_masks;
    delete r->offscreen_masks;
    vkDestroyDescriptorPool(device, r->descriptor_pool, NULL);
    vkUnmapMemory(device, r->ring_memory);
    vkDestroyBuffer(device, r->ring, NULL);
    vkFreeMemory(device, r->ring_memory, NULL);
    vkDestroyBuffer(device, r->static_buffer, NULL);
    vkFreeMemory(device, r->static_memory, NULL);
    for (VkFence fence : r->fences)
    {
        vkDestroyFence(device, fence, NULL);
    }
    vkDestroyCommandPool(device, r->pool, NULL);
    delete r;
}

static void ensure_targets(renderer* r, VkExtent2D extent)
{
    if (r->color.image != VK_NULL_HANDLE && r->extent.width == extent.width && r->extent.height == extent.height)
    {
        return;
    }
    vkWaitForFences(device, 2, r->fences, VK_TRUE, UINT64_MAX);
    release_targets(r);
    r->extent = extent;
    r->generation = ++target_generation;
    VkImageUsageFlags sampled = VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT | VK_IMAGE_USAGE_SAMPLED_BIT | VK_IMAGE_USAGE_TRANSFER_SRC_BIT;
    make_image(r->color, extent.width, extent.height, sample_count, r->blend ? sampled : VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT | VK_IMAGE_USAGE_TRANSIENT_ATTACHMENT_BIT);
    make_image(r->resolved, extent.width, extent.height, VK_SAMPLE_COUNT_1_BIT, sampled);
    if (!r->blend)
    {
        return;
    }
    make_image(r->snapshot, extent.width, extent.height, sample_count, VK_IMAGE_USAGE_TRANSFER_DST_BIT | VK_IMAGE_USAGE_SAMPLED_BIT);
    int32_t layers = 0;
    for (int32_t layer : r->offscreen_layer)
    {
        layers = std::max(layers, layer);
    }
    r->layers.resize((size_t)layers);
    for (gpu_image& layer : r->layers)
    {
        make_image(layer, extent.width, extent.height, sample_count, sampled);
    }
    for (size_t set = 0; set < r->target_sets.size(); set++)
    {
        VkDescriptorImageInfo images[layer_limit];
        for (uint32_t i = 0; i < layer_limit; i++)
        {
            images[i] = {nearest_sampler, i == 1 && set < r->layers.size() ? r->layers[set].view : r->snapshot.view, VK_IMAGE_LAYOUT_GENERAL};
        }
        VkWriteDescriptorSet write{};
        write.sType = VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET;
        write.dstSet = r->target_sets[set];
        write.descriptorCount = layer_limit;
        write.descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
        write.pImageInfo = images;
        vkUpdateDescriptorSets(device, 1, &write, 0, NULL);
    }
    if (r->drawable_masks != NULL || r->offscreen_masks != NULL)
    {
        make_mask(r, tile_side(r));
    }
    r->fresh = true;
}

static void end_target(renderer* r, VkCommandBuffer commands)
{
    if (r->open == -2)
    {
        return;
    }
    vkCmdEndRendering(commands);
    memory_barrier(commands);
    r->open = -2;
}

static void begin_rendering(VkCommandBuffer commands, VkImageView view, VkImageLayout layout, VkAttachmentLoadOp load, VkAttachmentStoreOp store, VkImageView resolve, VkExtent2D extent, float clear)
{
    VkRenderingAttachmentInfo attachment{};
    attachment.sType = VK_STRUCTURE_TYPE_RENDERING_ATTACHMENT_INFO;
    attachment.imageView = view;
    attachment.imageLayout = layout;
    attachment.loadOp = load;
    attachment.storeOp = store;
    attachment.clearValue.color = {{clear, clear, clear, clear}};
    attachment.resolveMode = resolve != VK_NULL_HANDLE ? VK_RESOLVE_MODE_AVERAGE_BIT : VK_RESOLVE_MODE_NONE;
    attachment.resolveImageView = resolve;
    attachment.resolveImageLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
    VkRenderingInfo rendering{};
    rendering.sType = VK_STRUCTURE_TYPE_RENDERING_INFO;
    rendering.renderArea = {{0, 0}, extent};
    rendering.layerCount = 1;
    rendering.colorAttachmentCount = 1;
    rendering.pColorAttachments = &attachment;
    vkCmdBeginRendering(commands, &rendering);
    VkViewport viewport = {0, 0, (float)extent.width, (float)extent.height, 0, 1};
    VkRect2D scissor = {{0, 0}, extent};
    vkCmdSetViewport(commands, 0, 1, &viewport);
    vkCmdSetScissor(commands, 0, 1, &scissor);
}

static void begin_target(renderer* r, VkCommandBuffer commands, int32_t target, bool clear)
{
    if (r->open == target && !clear)
    {
        return;
    }
    end_target(r, commands);
    VkImageView view = target < 0 ? r->color.view : r->layers[target - 1].view;
    begin_rendering(commands, view, VK_IMAGE_LAYOUT_GENERAL, clear ? VK_ATTACHMENT_LOAD_OP_CLEAR : VK_ATTACHMENT_LOAD_OP_LOAD, VK_ATTACHMENT_STORE_OP_STORE, VK_NULL_HANDLE, r->extent, 0.0f);
    r->open = target;
}

static void snapshot(renderer* r, VkCommandBuffer commands)
{
    int32_t target = r->open;
    end_target(r, commands);
    VkImageCopy region{};
    region.srcSubresource = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 0, 1};
    region.dstSubresource = region.srcSubresource;
    region.extent = {r->extent.width, r->extent.height, 1};
    vkCmdCopyImage(commands, (target < 0 ? r->color.image : r->layers[target - 1].image), VK_IMAGE_LAYOUT_GENERAL, r->snapshot.image, VK_IMAGE_LAYOUT_GENERAL, 1, &region);
    memory_barrier(commands);
    begin_target(r, commands, target, false);
}

static draw_data* next_draw(renderer* r, uint32_t& offset)
{
    offset = (uint32_t)(r->slot * r->slot_size + r->uniform_offset + (VkDeviceSize)r->draw_count * r->uniform_stride);
    r->draw_count++;
    return (draw_data*)(r->ring_mapped + offset);
}

static void issue(renderer* r, VkCommandBuffer commands, VkPipeline pipeline, bool cull, uint32_t offset, uint32_t count, uint32_t first, int32_t vertex)
{
    if (r->bound_pipeline != pipeline)
    {
        vkCmdBindPipeline(commands, VK_PIPELINE_BIND_POINT_GRAPHICS, pipeline);
        r->bound_pipeline = pipeline;
    }
    if (r->bound_cull != (int32_t)cull)
    {
        vkCmdSetCullMode(commands, cull ? VK_CULL_MODE_BACK_BIT : VK_CULL_MODE_NONE);
        r->bound_cull = (int32_t)cull;
    }
    vkCmdBindDescriptorSets(commands, VK_PIPELINE_BIND_POINT_GRAPHICS, pipeline_layout, 0, 1, &r->set, 1, &offset);
    vkCmdDrawIndexed(commands, count, 1, first, vertex, 0);
}

static void set_colors(draw_data* data, float opacity, const CubismRenderer::CubismTextureColor& multiply, const CubismRenderer::CubismTextureColor& screen)
{
    float multiply_values[4] = {multiply.R, multiply.G, multiply.B, multiply.A};
    float screen_values[4] = {screen.R, screen.G, screen.B, screen.A};
    float base[4] = {opacity, opacity, opacity, opacity};
    memcpy(data->base, base, sizeof(base));
    memcpy(data->multiply, multiply_values, sizeof(multiply_values));
    memcpy(data->screen, screen_values, sizeof(screen_values));
}

static void set_clip(draw_data* data, mask_manager* manager, mask_context* clip)
{
    CubismRenderer::CubismTextureColor* channel = manager->GetChannelFlagAsColor(clip->_layoutChannelIndex);
    float values[4] = {channel->R, channel->G, channel->B, channel->A};
    memcpy(data->clip_matrix, clip->_matrixForDraw.GetArray(), 64);
    memcpy(data->channel, values, sizeof(values));
    data->index[3] = clip->tile;
}

static void draw_masks(renderer* r, VkCommandBuffer commands, mask_manager* manager, CubismRenderer::DrawableObjectType type, const CubismMatrix44& mvp, uint32_t side)
{
    CubismModel* model = r->model;
    if (manager == NULL || manager->layout(*model, type, r->blend, type == CubismRenderer::DrawableObjectType_Offscreen ? mvp : CubismMatrix44()) <= 0)
    {
        return;
    }
    for (csmUint32 i = 0; i < manager->_clippingContextListForMask.GetSize(); i++)
    {
        mask_context* context = manager->_clippingContextListForMask[i];
        if (r->blend && !context->_isUsing)
        {
            continue;
        }
        VkViewport viewport = {0, (float)(context->tile * side), (float)side, (float)side, 0, 1};
        VkRect2D scissor = {{0, (int32_t)(context->tile * side)}, {side, side}};
        vkCmdSetViewport(commands, 0, 1, &viewport);
        vkCmdSetScissor(commands, 0, 1, &scissor);
        CubismRenderer::CubismTextureColor* channel = manager->GetChannelFlagAsColor(context->_layoutChannelIndex);
        csmRectF* rect = context->_layoutBounds;
        for (csmInt32 j = 0; j < context->_clippingIdCount; j++)
        {
            csmInt32 index = context->_clippingIdList[j];
            csmInt32 texture = model->GetDrawableTextureIndex(index);
            if (!model->GetDrawableDynamicFlagVertexPositionsDidChange(index) || model->GetDrawableVertexIndexCount(index) == 0 || texture < 0 || texture >= (csmInt32)texture_limit)
            {
                continue;
            }
            uint32_t offset = 0;
            draw_data* data = next_draw(r, offset);
            float bounds[4] = {rect->X * 2.0f - 1.0f, rect->Y * 2.0f - 1.0f, rect->GetRight() * 2.0f - 1.0f, rect->GetBottom() * 2.0f - 1.0f};
            float values[4] = {channel->R, channel->G, channel->B, channel->A};
            uint32_t ids[4] = {(uint32_t)texture, 0, 0, 0};
            memcpy(data->clip_matrix, context->_matrixForMask.GetArray(), 64);
            memcpy(data->base, bounds, sizeof(bounds));
            memcpy(data->channel, values, sizeof(values));
            memcpy(data->index, ids, sizeof(ids));
            issue(r, commands, mask_pipeline, model->GetDrawableCulling(index) != 0, offset, (uint32_t)model->GetDrawableVertexIndexCount(index), r->first_index[index], r->vertex_offset[index]);
        }
    }
}

static int fixed_blend(const csmBlendMode& mode)
{
    if (mode.GetColorBlendType() == Core::csmColorBlendType_AddCompatible)
    {
        return 1;
    }
    if (mode.GetColorBlendType() == Core::csmColorBlendType_MultiplyCompatible)
    {
        return 2;
    }
    return mode.GetColorBlendType() == Core::csmColorBlendType_Normal && mode.GetAlphaBlendType() == Core::csmAlphaBlendType_Over ? 0 : -1;
}

static void draw_offscreen(renderer* r, VkCommandBuffer commands, int32_t offscreen)
{
    CubismModel* model = r->model;
    r->current = r->offscreen_parent[offscreen];
    begin_target(r, commands, (r->current >= 0 ? r->offscreen_layer[r->current] : -1), false);
    mask_context* clip = r->offscreen_masks != NULL ? (*r->offscreen_masks->GetClippingContextListForOffscreen())[offscreen] : NULL;
    csmBlendMode mode = model->GetOffscreenBlendModeType(offscreen);
    int fixed = fixed_blend(mode);
    if (fixed < 0)
    {
        snapshot(r, commands);
    }
    uint32_t offset = 0;
    draw_data* data = next_draw(r, offset);
    uint32_t ids[4] = {0, 0, 1, 0};
    memcpy(data->matrix, identity, sizeof(identity));
    memcpy(data->index, ids, sizeof(ids));
    set_colors(data, model->GetOffscreenOpacity(offscreen), model->GetOverrideMultiplyAndScreenColor().GetOffscreenMultiplyColor(offscreen), model->GetOverrideMultiplyAndScreenColor().GetOffscreenScreenColor(offscreen));
    if (clip != NULL)
    {
        set_clip(data, r->offscreen_masks, clip);
    }
    int mask_mode = clip == NULL ? 0 : (model->GetOffscreenInvertedMask(offscreen) ? 2 : 1);
    int color = mode.GetColorBlendType();
    VkPipeline pipeline = blend_pipeline(mask_mode, fixed >= 0 ? -1 : (color == Core::csmColorBlendType_Normal ? 0 : color - 2), fixed >= 0 ? 0 : mode.GetAlphaBlendType(), 1, std::max(fixed, 0));
    vkCmdBindDescriptorSets(commands, VK_PIPELINE_BIND_POINT_GRAPHICS, pipeline_layout, 1, 1, &r->target_sets[r->offscreen_layer[offscreen] - 1], 0, NULL);
    issue(r, commands, pipeline, model->GetOffscreenCulling(offscreen) != 0, offset, 6, r->quad_index, (int32_t)r->quad_vertex);
}

static void submit_to_parent(renderer* r, VkCommandBuffer commands, csmInt32 object, bool is_offscreen)
{
    CubismModel* model = r->model;
    while (r->current >= 0 && object != CubismModel::CubismNoIndex_Offscreen)
    {
        csmInt32 owner = model->GetOffscreenOwnerIndices()[r->current];
        if (owner == CubismModel::CubismNoIndex_Offscreen)
        {
            return;
        }
        csmInt32 parent = is_offscreen ? model->GetPartParentPartIndex(model->GetOffscreenOwnerIndices()[object]) : model->GetDrawableParentPartIndex(object);
        for (; parent != CubismModel::CubismNoIndex_Parent; parent = model->GetPartParentPartIndex(parent))
        {
            if (parent == owner)
            {
                return;
            }
        }
        draw_offscreen(r, commands, r->current);
    }
}

static void add_offscreen(renderer* r, VkCommandBuffer commands, int32_t offscreen)
{
    CubismModel* model = r->model;
    if (r->current >= 0 && r->current != offscreen)
    {
        csmInt32 owner = model->GetOffscreenOwnerIndices()[r->current];
        bool is_parent = false;
        for (csmInt32 parent = model->GetPartParentPartIndex(model->GetOffscreenOwnerIndices()[offscreen]); parent != CubismModel::CubismNoIndex_Parent && !is_parent; parent = model->GetPartParentPartIndex(parent))
        {
            is_parent = parent == owner;
        }
        if (!is_parent)
        {
            submit_to_parent(r, commands, offscreen, true);
        }
    }
    begin_target(r, commands, r->offscreen_layer[offscreen], true);
    r->current = offscreen;
}

static void draw_drawable(renderer* r, VkCommandBuffer commands, csmInt32 index, const float* mvp)
{
    CubismModel* model = r->model;
    if (!model->GetDrawableDynamicFlagIsVisible(index))
    {
        return;
    }
    submit_to_parent(r, commands, index, false);
    mask_context* clip = r->drawable_masks != NULL ? (*r->drawable_masks->GetClippingContextListForDraw())[index] : NULL;
    csmInt32 texture = model->GetDrawableTextureIndex(index);
    if (model->GetDrawableVertexIndexCount(index) == 0 || model->GetDrawableOpacity(index) <= 0.0f || texture < 0 || texture >= (csmInt32)texture_limit)
    {
        return;
    }
    begin_target(r, commands, (r->current >= 0 ? r->offscreen_layer[r->current] : -1), false);
    csmBlendMode mode = model->GetDrawableBlendModeType(index);
    int fixed = fixed_blend(mode);
    if (fixed < 0)
    {
        snapshot(r, commands);
    }
    uint32_t offset = 0;
    draw_data* data = next_draw(r, offset);
    uint32_t ids[4] = {(uint32_t)texture, 0, 0, 0};
    memcpy(data->matrix, mvp, 64);
    memcpy(data->index, ids, sizeof(ids));
    set_colors(data, model->GetDrawableOpacity(index), model->GetOverrideMultiplyAndScreenColor().GetDrawableMultiplyColor(index), model->GetOverrideMultiplyAndScreenColor().GetDrawableScreenColor(index));
    if (clip != NULL)
    {
        set_clip(data, r->drawable_masks, clip);
    }
    int mask_mode = clip == NULL ? 0 : (model->GetDrawableInvertedMask(index) ? 2 : 1);
    int color = mode.GetColorBlendType();
    VkPipeline pipeline = fixed >= 0 ? model_pipelines[mask_mode][fixed] : blend_pipeline(mask_mode, color == Core::csmColorBlendType_Normal ? 0 : color - 2, mode.GetAlphaBlendType(), 0, 0);
    issue(r, commands, pipeline, model->GetDrawableCulling(index) != 0, offset, (uint32_t)model->GetDrawableVertexIndexCount(index), r->first_index[index], r->vertex_offset[index]);
}

VkCommandBuffer renderer_begin(renderer* r)
{
    vkWaitForFences(device, 1, &r->fences[r->slot], VK_TRUE, UINT64_MAX);
    VkCommandBuffer commands = r->commands[r->slot];
    vkResetCommandBuffer(commands, 0);
    VkCommandBufferBeginInfo begin{};
    begin.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO;
    begin.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
    vkBeginCommandBuffer(commands, &begin);
    return commands;
}

void renderer_draw(renderer* r, VkCommandBuffer commands, VkExtent2D extent, const float* mvp, VkImageLayout layout, VkPipelineStageFlags stage, VkAccessFlags access)
{
    CubismModel* model = r->model;
    ensure_targets(r, extent);
    mask_manager* masks = r->drawable_masks != NULL ? r->drawable_masks : r->offscreen_masks;
    uint32_t side = min_mask_side;
    if (masks != NULL && r->blend)
    {
        side = tile_side(r);
    }
    else if (masks != NULL)
    {
        float half_width = extent.width * 0.5f;
        float half_height = extent.height * 0.5f;
        float canvas_side = std::min(std::max(std::hypot(mvp[0] * half_width, mvp[1] * half_height) * model->GetCanvasWidth(), std::hypot(mvp[4] * half_width, mvp[5] * half_height) * model->GetCanvasHeight()), 4.0f * std::max(half_width, half_height));
        while (side < std::ceil(canvas_side) && side < 4096)
        {
            side *= 2;
        }
        if (side != r->mask_side)
        {
            vkWaitForFences(device, 2, r->fences, VK_TRUE, UINT64_MAX);
            make_mask(r, side);
            r->mask_side = side;
            for (mask_manager* manager : {r->drawable_masks, r->offscreen_masks})
            {
                if (manager != NULL)
                {
                    manager->SetClippingMaskBufferSize((float)side, (float)side);
                }
            }
        }
    }
    csmInt32 drawables = model->GetDrawableCount();
    csmInt32 total = drawables + model->GetOffscreenCount();
    uint8_t* positions = r->ring_mapped + r->slot * r->slot_size;
    for (csmInt32 i = 0; i < drawables; i++)
    {
        memcpy(positions + (size_t)r->vertex_offset[i] * 8, model->GetDrawableVertices(i), (size_t)model->GetDrawableVertexCount(i) * 8);
    }
    memcpy(positions + (size_t)r->quad_vertex * 8, quad_positions, sizeof(quad_positions));
    r->draw_count = 0;
    r->bound_pipeline = VK_NULL_HANDLE;
    r->bound_cull = -1;
    r->current = -1;
    r->open = -2;
    VkBuffer buffers[2] = {r->ring, r->static_buffer};
    VkDeviceSize offsets[2] = {r->slot * r->slot_size, 0};
    vkCmdBindVertexBuffers(commands, 0, 2, buffers, offsets);
    vkCmdBindIndexBuffer(commands, r->static_buffer, r->index_offset, VK_INDEX_TYPE_UINT16);
    if (r->blend)
    {
        vkCmdBindDescriptorSets(commands, VK_PIPELINE_BIND_POINT_GRAPHICS, pipeline_layout, 1, 1, &r->target_sets[0], 0, NULL);
    }
    image_barrier(commands, r->mask.image, VK_IMAGE_LAYOUT_UNDEFINED, VK_IMAGE_LAYOUT_GENERAL, VK_PIPELINE_STAGE_FRAGMENT_SHADER_BIT, 0, VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT, VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT);
    begin_rendering(commands, r->mask.view, VK_IMAGE_LAYOUT_GENERAL, VK_ATTACHMENT_LOAD_OP_CLEAR, VK_ATTACHMENT_STORE_OP_STORE, VK_NULL_HANDLE, VkExtent2D{side, side * r->mask_tiles}, 1.0f);
    CubismMatrix44 projection;
    projection.SetMatrix(const_cast<float*>(mvp));
    draw_masks(r, commands, r->drawable_masks, CubismRenderer::DrawableObjectType_Drawable, projection, side);
    draw_masks(r, commands, r->offscreen_masks, CubismRenderer::DrawableObjectType_Offscreen, projection, side);
    vkCmdEndRendering(commands);
    image_barrier(commands, r->mask.image, VK_IMAGE_LAYOUT_GENERAL, VK_IMAGE_LAYOUT_GENERAL, VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT, VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT, VK_PIPELINE_STAGE_FRAGMENT_SHADER_BIT, VK_ACCESS_SHADER_READ_BIT);
    image_barrier(commands, r->resolved.image, VK_IMAGE_LAYOUT_UNDEFINED, VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL, VK_PIPELINE_STAGE_TRANSFER_BIT | VK_PIPELINE_STAGE_FRAGMENT_SHADER_BIT, 0, VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT, VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT);
    if (r->blend)
    {
        if (r->fresh)
        {
            image_barrier(commands, r->color.image, VK_IMAGE_LAYOUT_UNDEFINED, VK_IMAGE_LAYOUT_GENERAL, VK_PIPELINE_STAGE_TOP_OF_PIPE_BIT, 0, VK_PIPELINE_STAGE_ALL_COMMANDS_BIT, 0);
            image_barrier(commands, r->snapshot.image, VK_IMAGE_LAYOUT_UNDEFINED, VK_IMAGE_LAYOUT_GENERAL, VK_PIPELINE_STAGE_TOP_OF_PIPE_BIT, 0, VK_PIPELINE_STAGE_ALL_COMMANDS_BIT, 0);
            for (gpu_image& layer : r->layers)
            {
                image_barrier(commands, layer.image, VK_IMAGE_LAYOUT_UNDEFINED, VK_IMAGE_LAYOUT_GENERAL, VK_PIPELINE_STAGE_TOP_OF_PIPE_BIT, 0, VK_PIPELINE_STAGE_ALL_COMMANDS_BIT, 0);
            }
        }
        r->fresh = false;
        memory_barrier(commands);
        begin_target(r, commands, -1, true);
    }
    else
    {
        image_barrier(commands, r->color.image, VK_IMAGE_LAYOUT_UNDEFINED, VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL, VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT, 0, VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT, VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT);
        begin_rendering(commands, r->color.view, VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL, VK_ATTACHMENT_LOAD_OP_CLEAR, VK_ATTACHMENT_STORE_OP_DONT_CARE, r->resolved.view, r->extent, 0.0f);
        r->open = -1;
    }
    const csmInt32* orders = model->GetRenderOrders();
    for (csmInt32 i = 0; i < total; i++)
    {
        r->sorted[orders[i]] = i;
    }
    for (csmInt32 i = 0; i < total; i++)
    {
        if (r->sorted[i] < drawables)
        {
            draw_drawable(r, commands, r->sorted[i], mvp);
        }
        else
        {
            add_offscreen(r, commands, r->sorted[i] - drawables);
        }
    }
    while (r->current >= 0)
    {
        submit_to_parent(r, commands, r->current, true);
    }
    if (r->blend)
    {
        end_target(r, commands);
        begin_rendering(commands, r->color.view, VK_IMAGE_LAYOUT_GENERAL, VK_ATTACHMENT_LOAD_OP_LOAD, VK_ATTACHMENT_STORE_OP_DONT_CARE, r->resolved.view, r->extent, 0.0f);
    }
    vkCmdEndRendering(commands);
    image_barrier(commands, r->resolved.image, VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL, layout, VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT, VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT, stage, access);
}

void renderer_submit(renderer* r, VkSemaphore wait, VkPipelineStageFlags wait_stage, VkSemaphore signal)
{
    VkCommandBuffer commands = r->commands[r->slot];
    vkEndCommandBuffer(commands);
    vkResetFences(device, 1, &r->fences[r->slot]);
    VkSubmitInfo submit{};
    submit.sType = VK_STRUCTURE_TYPE_SUBMIT_INFO;
    submit.waitSemaphoreCount = wait != VK_NULL_HANDLE ? 1 : 0;
    submit.pWaitSemaphores = &wait;
    submit.pWaitDstStageMask = &wait_stage;
    submit.commandBufferCount = 1;
    submit.pCommandBuffers = &commands;
    submit.signalSemaphoreCount = signal != VK_NULL_HANDLE ? 1 : 0;
    submit.pSignalSemaphores = &signal;
    std::lock_guard<std::mutex> guard(*queue_lock);
    vkQueueSubmit(queue, 1, &submit, r->fences[r->slot]);
    r->slot ^= 1;
}
