csmInt32 mask_manager::layout(CubismModel& model, CubismRenderer::DrawableObjectType type, bool high_precision, const CubismMatrix44& mvp)
{
    if (high_precision)
    {
        SetupMatrixForHighPrecision(model, false, type, mvp);
        return 1;
    }
    csmInt32 using_count = 0;
    for (csmUint32 i = 0; i < _clippingContextListForMask.GetSize(); i++)
    {
        CalcClippedTotalBounds(model, _clippingContextListForMask[i], type);
        using_count += _clippingContextListForMask[i]->_isUsing ? 1 : 0;
    }
    if (using_count <= 0)
    {
        return 0;
    }
    SetupLayoutBounds(using_count);
    for (csmUint32 i = 0; i < _clippingContextListForMask.GetSize(); i++)
    {
        mask_context* context = _clippingContextListForMask[i];
        _tmpBoundsOnModel.SetRect(context->_allClippedDrawRect);
        _tmpBoundsOnModel.Expand(context->_allClippedDrawRect->Width * 0.05f, context->_allClippedDrawRect->Height * 0.05f);
        CreateMatrixForMask(false, context->_layoutBounds, context->_layoutBounds->Width / _tmpBoundsOnModel.Width, context->_layoutBounds->Height / _tmpBoundsOnModel.Height);
        context->_matrixForMask.SetMatrix(_tmpMatrixForMask.GetArray());
        context->_matrixForDraw.SetMatrix(_tmpMatrixForDraw.GetArray());
    }
    return using_count;
}

static VkDeviceMemory allocate(VkMemoryRequirements requirements, VkMemoryPropertyFlags wanted, VkMemoryPropertyFlags fallback)
{
    uint32_t chosen = UINT32_MAX;
    for (VkMemoryPropertyFlags flags : {wanted, fallback})
    {
        for (uint32_t i = 0; i < memory_properties.memoryTypeCount; i++)
        {
            if (chosen == UINT32_MAX && (requirements.memoryTypeBits & (1u << i)) && (memory_properties.memoryTypes[i].propertyFlags & flags) == flags)
            {
                chosen = i;
            }
        }
    }
    VkMemoryAllocateInfo info{};
    info.sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO;
    info.allocationSize = requirements.size;
    info.memoryTypeIndex = chosen;
    VkDeviceMemory memory = VK_NULL_HANDLE;
    vkAllocateMemory(device, &info, NULL, &memory);
    return memory;
}

static void make_buffer(VkDeviceSize size, VkBufferUsageFlags usage, VkMemoryPropertyFlags wanted, VkMemoryPropertyFlags fallback, VkBuffer& buffer, VkDeviceMemory& memory)
{
    VkBufferCreateInfo info{};
    info.sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO;
    info.size = size;
    info.usage = usage;
    info.sharingMode = VK_SHARING_MODE_EXCLUSIVE;
    vkCreateBuffer(device, &info, NULL, &buffer);
    VkMemoryRequirements requirements;
    vkGetBufferMemoryRequirements(device, buffer, &requirements);
    memory = allocate(requirements, wanted, fallback);
    vkBindBufferMemory(device, buffer, memory, 0);
}

static void make_image(gpu_image& image, uint32_t width, uint32_t height, VkSampleCountFlagBits samples, VkImageUsageFlags usage)
{
    VkImageCreateInfo info{};
    info.sType = VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO;
    info.imageType = VK_IMAGE_TYPE_2D;
    info.format = color_format;
    info.extent = {width, height, 1};
    info.mipLevels = 1;
    info.arrayLayers = 1;
    info.samples = samples;
    info.tiling = VK_IMAGE_TILING_OPTIMAL;
    info.usage = usage;
    info.sharingMode = VK_SHARING_MODE_EXCLUSIVE;
    info.initialLayout = VK_IMAGE_LAYOUT_UNDEFINED;
    vkCreateImage(device, &info, NULL, &image.image);
    VkMemoryRequirements requirements;
    vkGetImageMemoryRequirements(device, image.image, &requirements);
    VkMemoryPropertyFlags lazy = (usage & VK_IMAGE_USAGE_TRANSIENT_ATTACHMENT_BIT) ? VK_MEMORY_PROPERTY_LAZILY_ALLOCATED_BIT : 0;
    image.memory = allocate(requirements, VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT | lazy, VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT);
    vkBindImageMemory(device, image.image, image.memory, 0);
    VkImageViewCreateInfo view{};
    view.sType = VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO;
    view.image = image.image;
    view.viewType = VK_IMAGE_VIEW_TYPE_2D;
    view.format = color_format;
    view.subresourceRange = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1};
    vkCreateImageView(device, &view, NULL, &image.view);
}

static void release_image(gpu_image& image)
{
    vkDestroyImageView(device, image.view, NULL);
    vkDestroyImage(device, image.image, NULL);
    vkFreeMemory(device, image.memory, NULL);
    image = gpu_image();
}

